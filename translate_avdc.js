const filePath = '/Users/bangchangkim/vetool_wondang/constants/hospital/dental/avdcAbbreviations.ts';
let text = fs.readFileSync(filePath, 'utf-8');

const lines = text.split('\n');
const newLines = lines.map(line => {
    if (line.includes('definition_kr:')) return line;
    
    const match = line.match(/\{\s*abbr:\s*['"](.*?)['"],\s*definition:\s*['"](.*?)['"],/);
    if (!match) return line;

    const abbr = match[1];
    let trans = translations[abbr];
    if (!trans) {
        if (abbr.includes('I1,2,3')) trans = '절치 (앞니)';
        else if (abbr.includes('M1,2,3')) trans = '구치 (어금니)';
        else if (abbr.includes('PM1-4')) trans = '소구치 (작은어금니)';
    }

    if (!trans) return line;

    return line.replace(/(definition:\s*['"][^'"]+['"],)/, `$1  definition_kr: '${trans}',`);
});

fs.writeFileSync(filePath, newLines.join('\n'), 'utf-8');
console.log('Successfully updated with definition_kr via JavaScript!');
